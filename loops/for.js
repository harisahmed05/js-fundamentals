// Printing all even numbers from 0 to 12 - using for loop
for(let number = 0; number <= 12; number = number + 2) {
    console.log(number);
}

// Generating 2 to the power 10 - using for loop
let result = 1;
for(let counter = 0; counter < 10; counter = counter + 1) {
    result = result * 2;
}
console.log(result);
